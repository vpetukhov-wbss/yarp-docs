#!/usr/bin/env node
// Generates src/app/core/prerender-slugs.generated.ts from the same
// ia.mjs ALL_ITEMS table build-content.mjs and build-sitemap.mjs use, so
// app.routes.server.ts's getPrerenderParams() can enumerate every doc slug
// at build time without importing a .mjs script from outside src/ (which
// the Angular application builder doesn't resolve).
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { ALL_ITEMS } from '../content/ia.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUTPUT_PATH = join(__dirname, '..', '..', 'src', 'app', 'core', 'prerender-slugs.generated.ts');

function main() {
  const slugs = ALL_ITEMS.map((item) => item.slug);
  const body =
    '// AUTO-GENERATED by scripts/seo/build-prerender-routes.mjs from ia.mjs - do not edit by hand.\n' +
    `export const PRERENDER_SLUGS: readonly string[] = ${JSON.stringify(slugs, null, 2)};\n`;
  writeFileSync(OUTPUT_PATH, body, 'utf8');
  console.log(`Wrote ${OUTPUT_PATH} (${slugs.length} slugs).`);
}

// pathToFileURL handles Windows drive-letter casing, backslashes, and
// spaces correctly, unlike a hand-rolled string comparison - see
// build-content.mjs's identical guard.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
